export function computeRestartResult(selection) {
  if (!Array.isArray(selection) || selection.length !== 3) return null
  if (new Set(selection).size !== 3) return null
  if (!selection.every((key) => typeof key === 'string' && choiceByKey[key])) return null

  const selectedChoices = selection.map((key) => choiceByKey[key])
  const primaryKey = selectedChoices[0].category
  const secondaryIndex = selectedChoices.findIndex((choice, index) => index > 0 && choice.category !== primaryKey)
  if (secondaryIndex < 1) return null

  const secondaryKey = selectedChoices[secondaryIndex].category
  const combinationKey = `${primaryKey}>${secondaryKey}`
  const combination = combinations[combinationKey]
  if (!combination) return null

  const evidence = [
    `第一槽保留“${selectedChoices[0].short}”，说明你会先靠${categories[primaryKey].method}夺回主动权。`,
    `第${secondaryIndex + 1}槽首次转向“${selectedChoices[secondaryIndex].short}”，${categories[secondaryKey].name}是你的第二套重启系统。`,
    `三项选择依次为 ${selection.join(' → ')}。同样的能力换一个顺序，主副模型也会改变。`,
  ]

  return {
    key: combinationKey,
    primary: categories[primaryKey],
    secondary: categories[secondaryKey],
    selection: selectedChoices,
    evidence,
    ...combination,
  }
}
