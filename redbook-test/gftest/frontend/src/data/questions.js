export function computeDimensions(answers) {
  const tagCounts = {}
  answers.forEach(opt => {
    (opt.tags || []).forEach(t => {
      tagCounts[t] = (tagCounts[t] || 0) + 1
    })
  })

  const dims = {}
  for (const [name, { pos, neg }] of Object.entries(dimMap)) {
    let score = 50 // 基准分
    pos.forEach(t => { score += (tagCounts[t] || 0) * 7 })
    neg.forEach(t => { score -= (tagCounts[t] || 0) * 7 })
    dims[name] = Math.max(5, Math.min(98, Math.round(score)))
  }
  return dims
}

// ===== 计算 Tag（归一化：稀有标签加权）=====
const tagWeights = (() => {
  const freq = {}
  questions.forEach(q => {
    q.options.forEach(opt => {
      (opt.tags || []).forEach(t => { freq[t] = (freq[t] || 0) + 1 })
    })
  })
  // 权重 = 1 / sqrt(频率)，稀有标签分更高
  const weights = {}
  for (const [t, n] of Object.entries(freq)) {
    weights[t] = 1 / Math.sqrt(n)
  }
  return weights
})()

export function computeTopTag(answers) {
  const scores = {}
  answers.forEach(opt => {
    (opt.tags || []).forEach(t => {
      scores[t] = (scores[t] || 0) + (tagWeights[t] || 0.3)
    })
  })
  const sorted = Object.entries(scores).sort((a, b) => b[1] - a[1])
  if (!sorted.length) return { key: '🌸', name: '温柔女友', icon: '🌸', desc: '信息太少，AI 也无法判断' }
  const [key, score] = sorted[0]
  return { key, count: Math.round(score * 10) / 10, ...tagMap[key] }
}

