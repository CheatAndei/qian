export const ARCHETYPE_ORDER = ['lv1', 'lv2', 'lv3', 'lv4', 'lv5', 'lv6']

const MAX_AXIS = questions.length * 3

export function computeReport(answers) {
  const warmth = Math.round((answers.reduce((s, a) => s + (a.invest || 0), 0) / MAX_AXIS) * 100)
  const stability = Math.round((answers.reduce((s, a) => s + (a.recip || 0), 0) / MAX_AXIS) * 100)
  const signal = Math.round(warmth * 0.55 + stability * 0.45)
  const scored = ARCHETYPE_ORDER.map((key) => {
    const [pw, ps] = archetypes[key].proto
    const dist = Math.hypot(warmth - pw, stability - ps)
    return { key, dist, w: Math.exp(-dist / 23) }
  })
  const wsum = scored.reduce((s, x) => s + x.w, 0) || 1
  const distribution = scored
    .map((x) => ({ key: x.key, name: archetypes[x.key].name, pct: Math.round((x.w / wsum) * 100) }))
    .sort((a, b) => b.pct - a.pct)
  const domKey = scored.reduce((a, b) => (b.w > a.w ? b : a)).key
  const idx = ARCHETYPE_ORDER.indexOf(domKey)
  return {
    invest: warmth,
    recip: stability,
    signal,
    key: domKey,
    archetype: archetypes[domKey],
    distribution,
    blip: { angle: -90 + idx * 60, radius: Math.max(24, signal) },
  }
}
